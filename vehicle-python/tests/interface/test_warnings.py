from pathlib import Path

import pytest
import vehicle_lang as vcl
from vehicle_lang.error import VehicleUserError

from ..config import HASKELL_GOLDEN_TESTS_PATH

TRIVIAL_PATH = HASKELL_GOLDEN_TESTS_PATH / "warnings" / "trivial"
BOUNDS_ONLY_PATH = HASKELL_GOLDEN_TESTS_PATH / "warnings" / "boundsOnlyQuantifier"


def compile_trivial_queries(output: Path, *extra_args: str) -> None:
    vcl.session.execute_command(
        [
            *extra_args,
            "compile",
            "queries",
            f"--specification={TRIVIAL_PATH / 'spec.vcl'}",
            "--format=MarabouQueries",
            f"--output={output}",
            f"--network=f:{TRIVIAL_PATH / 'fake.onnx'}",
        ]
    )


def test_warnings_are_printed(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """
    Tests that warnings generated by Vehicle are printed to stderr.
    """
    compile_trivial_queries(tmp_path / "queries")
    captured = capsys.readouterr()
    assert "Warning: The property 'p' was found to evaluate to 'True'" in captured.err


def test_warnings_are_printed_on_error(capsys: pytest.CaptureFixture[str]) -> None:
    """
    Tests that warnings generated by Vehicle are printed to stderr, even when
    Vehicle subsequently fails with an error.
    """
    with pytest.raises(VehicleUserError):
        vcl.loss.load_ast(BOUNDS_ONLY_PATH / "spec.vcl")
    captured = capsys.readouterr()
    assert "Warning:" in captured.err
    assert "'prop1'" in captured.err
    assert "'prop2'" in captured.err


def test_no_warnings_printed_when_suppressed(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """
    Tests that `--no-warnings` suppresses the printing of warnings.
    """
    compile_trivial_queries(tmp_path / "queries", "--no-warnings")
    captured = capsys.readouterr()
    assert "Warning:" not in captured.err
